"""
AnomalyX - AI-Powered MPLADS Monitoring & Risk Detection System
FastAPI Backend Reference Implementation
Compatible with Azure App Service / AKS, Azure SQL, and Azure ML
"""

from fastapi import FastAPI, Depends, HTTPException, status, Query
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, EmailStr
from typing import List, Optional, Dict, Any
from datetime import datetime
import enum

app = FastAPI(
    title="AnomalyX MPLADS API",
    description="AI-Powered MPLADS Early Warning & Risk-Prioritization Platform",
    version="1.0.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

class UserRole(str, enum.Enum):
    CONTRACTOR = "CONTRACTOR"
    PWD_ENGINEER = "PWD_ENGINEER"
    COLLECTOR = "COLLECTOR"
    CAG_AUDITOR = "CAG_AUDITOR"
    ADMIN = "ADMIN"

class RiskLevel(str, enum.Enum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"

class LoginRequest(BaseModel):
    identifier: str
    password: Optional[str] = None
    role: Optional[UserRole] = None

class TokenResponse(BaseModel):
    access_token: str
    token_type: str = "bearer"
    role: UserRole
    user_id: str
    full_name: str

class ProjectSchema(BaseModel):
    id: str
    code: str
    name: str
    category: str
    district: str
    state: str
    sanction_amount: float
    contract_amount: float
    expenditure: float
    physical_progress_percent: float
    financial_progress_percent: float
    risk_score: float
    risk_level: RiskLevel
    contractor_name: str

